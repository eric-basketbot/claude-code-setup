#!/usr/bin/env python3
"""Generate Codex instruction files from Claude-owned sources.

The default mode is read-only drift checking. Pass --write explicitly to update
targets. Generated files use deterministic LF newlines and a content digest.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import secrets
import stat
import subprocess
import sys
import tempfile
from typing import Any


DEFAULT_MANIFEST = Path("~/.claude/ai-config/sync-manifest.json")
GENERATED_PREFIX = "<!-- Generated by ~/.claude/scripts/sync-ai-config.py; body-sha256: "
GLOBAL_TARGET = Path("~/.codex/AGENTS.md")
GIT_BIN = "/usr/bin/git"


class SyncError(RuntimeError):
    """Raised when source configuration is incomplete or ambiguous."""


def expand_path(value: str) -> Path:
    return Path(os.path.expandvars(os.path.expanduser(value))).resolve()


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        raise SyncError(f"cannot read {path}: {error}") from error


def read_text_at(directory_fd: int, name: str, *, missing_ok: bool = False) -> str:
    """Read one regular file relative to an already validated directory."""
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(name, flags, dir_fd=directory_fd)
    except FileNotFoundError:
        if missing_ok:
            return ""
        raise SyncError(f"required project file is missing: {name}")
    try:
        if not stat.S_ISREG(os.fstat(descriptor).st_mode):
            raise SyncError(f"project file must be regular: {name}")
        with os.fdopen(descriptor, "r", encoding="utf-8") as handle:
            descriptor = -1
            return handle.read()
    finally:
        if descriptor >= 0:
            os.close(descriptor)


def normalized(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n").rstrip() + "\n"


def strip_source_metadata(text: str) -> str:
    """Remove Claude-only marker comments and one leading YAML frontmatter block."""
    lines = normalized(text).splitlines()
    lines = [
        line
        for line in lines
        if not re.fullmatch(r"<!--# (?:BEGIN|END) [^>]+ -->", line)
    ]
    while lines and not lines[0].strip():
        lines.pop(0)
    if lines and lines[0] == "---":
        try:
            end = lines.index("---", 1)
        except ValueError as error:
            raise SyncError("unterminated YAML frontmatter") from error
        lines = lines[end + 1 :]
    return normalized("\n".join(lines))


def shift_markdown_headings(text: str) -> str:
    """Nest a standalone source under the generated document's H1."""
    shifted: list[str] = []
    fence: str | None = None
    for line in normalized(text).splitlines():
        fence_match = re.match(r"^\s*(```|~~~)", line)
        if fence_match:
            marker = fence_match.group(1)
            if fence is None:
                fence = marker
            elif fence == marker:
                fence = None
            shifted.append(line)
            continue
        if fence is None:
            heading = re.match(r"^(#{1,5})(\s+.*)$", line)
            if heading:
                line = f"#{heading.group(1)}{heading.group(2)}"
        shifted.append(line)
    return normalized("\n".join(shifted))


def generated_document(body: str) -> str:
    clean_body = normalized(body)
    digest = hashlib.sha256(clean_body.encode("utf-8")).hexdigest()
    return f"{GENERATED_PREFIX}{digest} -->\n{clean_body}"


def render_global(config: dict[str, Any]) -> tuple[Path, str]:
    declared_target = expand_path(config["target"])
    target = expand_path(str(GLOBAL_TARGET))
    if declared_target != target:
        raise SyncError("global target must be ~/.codex/AGENTS.md")
    preamble = normalized(read_text(expand_path(config["preamble"]))).rstrip()
    appendix = normalized(read_text(expand_path(config["appendix"]))).rstrip()
    sources = [config["claude_source"], *config["rules"]]
    sections: list[str] = [preamble]
    for source_value in sources:
        source_path = expand_path(source_value)
        source_text = strip_source_metadata(read_text(source_path))
        source_label = source_path.relative_to(Path.home())
        sections.append(
            f"<!-- Source: ~/{source_label.as_posix()} -->\n\n"
            f"{shift_markdown_headings(source_text).rstrip()}"
        )
    sections.append(appendix)
    return target, generated_document("\n\n---\n\n".join(sections))


def project_headings(text: str) -> list[str]:
    return [line for line in normalized(text).splitlines() if line.startswith("## ")]


def remove_heading_section(text: str, heading: str) -> str:
    lines = normalized(text).splitlines()
    starts = [index for index, line in enumerate(lines) if line == heading]
    if len(starts) != 1:
        raise SyncError(f"expected one project section {heading!r}, found {len(starts)}")
    start = starts[0]
    end = next(
        (index for index in range(start + 1, len(lines)) if lines[index].startswith("## ")),
        len(lines),
    )
    del lines[start:end]
    while start < len(lines) and not lines[start].strip():
        del lines[start]
    return normalized("\n".join(lines))


def apply_explicit_substitutions(
    text: str, substitutions: list[dict[str, str]]
) -> str:
    result = text
    for substitution in substitutions:
        source = substitution["from"]
        replacement = substitution["to"]
        count = result.count(source)
        if count != 1:
            raise SyncError(
                f"expected explicit substitution source exactly once; found {count}: {source!r}"
            )
        result = result.replace(source, replacement, 1)
    return normalized(result)


def render_project(
    config: dict[str, Any],
    project_root: Path | None,
    directory_fd: int | None = None,
) -> tuple[Path, str]:
    root = project_root or expand_path(config["default_root"])
    root = root.resolve()
    if config.get("source") != "CLAUDE.md" or config.get("target") != "AGENTS.md":
        raise SyncError("project source/target must be CLAUDE.md and AGENTS.md")
    source_path = root / "CLAUDE.md"
    target = root / "AGENTS.md"
    source_text = normalized(
        read_text_at(directory_fd, "CLAUDE.md")
        if directory_fd is not None
        else read_text(source_path)
    )

    if not source_text.startswith("# CLAUDE.md — Context for Claude across sessions\n"):
        raise SyncError(f"unexpected project CLAUDE.md title in {source_path}")

    allowed = list(config["allowed_top_level_headings"])
    observed = project_headings(source_text)
    if observed != allowed:
        raise SyncError(
            "project CLAUDE.md headings must match the manifest exactly, "
            "once each and in declared order"
        )

    without_claude_host = remove_heading_section(
        source_text, config["excluded_heading"]
    )
    adapted = apply_explicit_substitutions(
        without_claude_host, config["substitutions"]
    )
    title, remainder = adapted.split("\n", 1)
    preamble = normalized(read_text(expand_path(config["preamble"]))).rstrip()
    body = f"{title}\n\n{preamble}\n\n{remainder.lstrip()}"
    return target, generated_document(body)


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = path.stat().st_mode & 0o777 if path.exists() else 0o644
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        try:
            temporary.unlink()
        except FileNotFoundError:
            pass


def atomic_write_at(directory_fd: int, name: str, content: str) -> None:
    """Atomically replace a regular project file through a pinned dir fd."""
    try:
        target_info = os.stat(name, dir_fd=directory_fd, follow_symlinks=False)
    except FileNotFoundError:
        mode = 0o644
    else:
        if not stat.S_ISREG(target_info.st_mode):
            raise SyncError(f"refusing non-regular project target: {name}")
        mode = stat.S_IMODE(target_info.st_mode)

    temporary_name = f".{name}.{os.getpid()}.{secrets.token_hex(8)}.tmp"
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
    descriptor = os.open(temporary_name, flags, 0o600, dir_fd=directory_fd)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            descriptor = -1
            handle.write(content)
            handle.flush()
            os.fchmod(handle.fileno(), mode)
            os.fsync(handle.fileno())
        os.replace(
            temporary_name,
            name,
            src_dir_fd=directory_fd,
            dst_dir_fd=directory_fd,
        )
        os.fsync(directory_fd)
    finally:
        if descriptor >= 0:
            os.close(descriptor)
        try:
            os.unlink(temporary_name, dir_fd=directory_fd)
        except FileNotFoundError:
            pass


def load_manifest(path: Path) -> dict[str, Any]:
    try:
        manifest = json.loads(read_text(path))
    except json.JSONDecodeError as error:
        raise SyncError(f"invalid manifest JSON at {path}: {error}") from error
    if manifest.get("schema_version") != 1:
        raise SyncError("unsupported sync manifest schema_version")
    return manifest


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument(
        "--check",
        action="store_true",
        help="check for drift without writing (default)",
    )
    action.add_argument(
        "--write",
        action="store_true",
        help="atomically update generated targets",
    )
    parser.add_argument(
        "--scope",
        choices=("all", "global", "project"),
        default="all",
        help="limit generation to one target class",
    )
    return parser.parse_args()


def validated_project_root(
    root: Path | None,
    config: dict[str, Any],
    *,
    writing: bool,
    fallback_to_canonical: bool = False,
) -> Path:
    declared_root = config.get("default_root")
    if not declared_root:
        raise SyncError("manifest is missing project.default_root")
    canonical = expand_path(declared_root)
    if not canonical.is_dir():
        raise SyncError(f"project.default_root does not exist: {canonical}")
    requested = root.resolve() if root is not None else canonical
    result = subprocess.run(
        [GIT_BIN, "-C", str(canonical), "worktree", "list", "--porcelain"],
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
        timeout=10,
        check=False,
    )
    if result.returncode != 0:
        raise SyncError("cannot enumerate <project> worktrees")
    allowed = [
        Path(line.removeprefix("worktree ")).resolve()
        for line in result.stdout.splitlines()
        if line.startswith("worktree ")
    ]
    matched = next(
        (
            candidate
            for candidate in allowed
            if candidate == requested or candidate in requested.parents
        ),
        None,
    )
    if matched is None and fallback_to_canonical and canonical in allowed:
        matched = canonical
    if matched is None:
        raise SyncError("project root must be a registered <project> worktree")
    if writing and matched == canonical:
        raise SyncError("refusing to write the canonical <project> checkout")
    return matched


def main() -> int:
    args = parse_args()
    project_fd: int | None = None
    try:
        if args.write and args.scope == "all":
            raise SyncError(
                "writes require an explicit --scope; use global, or run "
                "--scope project from an isolated worktree"
            )
        manifest = load_manifest(expand_path(str(DEFAULT_MANIFEST)))
        project_root: Path | None = None
        if args.scope in ("all", "project"):
            requested_root = Path.cwd()
            project_root = validated_project_root(
                requested_root,
                manifest["project"],
                writing=args.write,
                fallback_to_canonical=args.scope == "all",
            )
            open_flags = os.O_RDONLY | os.O_DIRECTORY | getattr(os, "O_NOFOLLOW", 0)
            project_fd = os.open(project_root, open_flags)
        outputs: list[tuple[Path, str, bool]] = []
        if args.scope in ("all", "global"):
            target, expected = render_global(manifest["global"])
            outputs.append((target, expected, False))
        if args.scope in ("all", "project"):
            target, expected = render_project(
                manifest["project"], project_root, project_fd
            )
            outputs.append((target, expected, True))

        drift = False
        for target, expected, is_project in outputs:
            actual = (
                read_text_at(project_fd, target.name, missing_ok=True)
                if is_project and project_fd is not None
                else read_text(target)
                if target.exists()
                else ""
            )
            if actual == expected:
                print(f"OK {target}")
                continue
            if args.write:
                if is_project and project_fd is not None:
                    atomic_write_at(project_fd, target.name, expected)
                else:
                    atomic_write(target, expected)
                print(f"WROTE {target}")
            else:
                drift = True
                print(f"DRIFT {target}")
        return 1 if drift else 0
    except (
        KeyError,
        TypeError,
        ValueError,
        OSError,
        SyncError,
        subprocess.SubprocessError,
    ) as error:
        print(f"ERROR {error}", file=sys.stderr)
        return 2
    finally:
        if project_fd is not None:
            os.close(project_fd)


if __name__ == "__main__":
    raise SystemExit(main())
